% 一次性更新测试计数 81 -> 82（r16 光流标度）
root = fileparts(fileparts(mfilename('fullpath')));
files = { ...
    fullfile(root, 'README.md'), ...
    fullfile(root, 'README.en.md'), ...
    fullfile(root, 'docs', 'validation.md')};

pairs = { ...
    "81 项全部通过", "82 项全部通过"; ...
    "81 项，约 70 s", "82 项，约 66 s"; ...
    "81 项测试逐条说明", "82 项测试逐条说明"; ...
    "81 tests, about 70 s", "82 tests, about 66 s"; ...
    "共 81 项", "共 82 项"; ...
    "`tEstimation` 8 项", "`tEstimation` 9 项"};

for k = 1:numel(files)
    f = files{k};
    if ~isfile(f), continue; end
    t = fileread(f);
    for j = 1:size(pairs, 1)
        t = strrep(t, pairs{j, 1}, pairs{j, 2});
    end
    fid = fopen(f, 'w', 'n', 'UTF-8');
    fwrite(fid, t);
    fclose(fid);
end
disp('counts updated to 82');
