function c = ctrl()
%CTRL  级联位置/姿态控制器增益。
%   位置环输出期望加速度（NED），由控制器换算为推力与期望姿态角。
%   姿态环为欧拉角 PD + 积分，输出机体力矩。

c.Kp = [1.6; 1.6; 2.5];             % 位置环 P，m/s^2 per m
c.Kd = [2.2; 2.2; 3.0];             % 位置环 D，m/s^2 per (m/s)
c.Ki = [0.0; 0.0; 1.2];             % 位置环 I
c.iMax = [0; 0; 1.0];               % 位置积分限幅

c.KpAtt = [6.0; 6.0; 3.0];          % 姿态环 P，N*m/rad
c.KdAtt = [0.35; 0.35; 0.30];       % 姿态环 D，N*m/(rad/s)
c.KiAtt = [0.0; 0.0; 0.15];         % 姿态环 I
c.iMaxAtt = [0.2; 0.2; 0.2];

c.maxTilt = 35*pi/180;              % 期望倾角限幅 rad
c.maxT    = 40;                     % 总推力限幅 N
c.maxM    = [3.0; 3.0; 1.5];        % 力矩限幅 N*m
end
