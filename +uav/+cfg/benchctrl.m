function b = benchctrl()
%BENCHCTRL  基准对比用的线性控制器权重。
%   与解析级联控制器（uav.cfg.ctrl）分开，避免影响已有的级联参数。

% LQR 状态权重：[位置; 速度; 姿态; 角速度]
